"""Figure 1 outside the PDF: the README block (data/money_readme.md) and the freshness stamp of money.png.

`just paper-refresh` exports docs/paper/money.png from figures/money_standalone.tex, then calls
`python -m tools.paper_data --publish`, which copies the generated block into README.md between its
markers and records the hash of the figure's inputs. A test compares both, so neither can go stale.
"""

from __future__ import annotations

from pathlib import Path
import hashlib

from .cold import speed_text
from .common import DATA, HOST_NAMES, PaperDataError, fmt
from .evidence import HEADLINE, derived

START, END = "<!-- money-plot:start -->", "<!-- money-plot:end -->"
FIGURE_INPUTS = ("docs/paper/data/cold_dev.csv", "docs/paper/data/money_layout.tex", "docs/paper/data/money_frontier.csv",
                 "docs/paper/figures/money.tex", "docs/paper/figures/style.tex", "docs/paper/figures/money_standalone.tex")
STAMP = "docs/paper/money.png.inputs"


LEAD = ("ULTRA is a small streaming transducer and an integer-exact Rust CPU engine built to listen all the time: every "
        "second of audio, speech or not, on a small share of one core. Measured beside the published CPU recognisers on "
        "our own hardware and under one protocol, it is less accurate than most of them and costs a fraction of their "
        "CPU time and watts.")


def readme_block(rows: list[dict], facts: dict, watts: str, always_on: str | None = None) -> str:
    """Markdown for the top of README.md: the figure, caption, lead, supporting facts and table."""
    drawn = [r for r in rows if (r["machine"], r["threads"]) == HEADLINE and r["plot"]]
    extra = [r for r in rows if r["variant"] == always_on and not r["plot"] and not r.get("anchor")
             and (r["machine"], r["threads"]) == HEADLINE]
    lines = [START, "<!-- Generated by `just paper-refresh` from docs/paper/data (evidence rows and receipts). "
             "Do not edit by hand. -->",
             "![Cold throughput per core against dev-clean WER on the 730-utterance LibriSpeech DEV panel]"
             "(docs/paper/money.png)", ""]
    if not drawn:
        lines += ["No measured rows yet.", END]
        return "\n".join(lines) + "\n"
    subset = (" The table marks runs timed on the 73-utterance subset of the panel."
              if any(r["timing_panel"] != "full" for r in drawn) else "")
    lines += [f"**Figure 1.** {facts['figure']} Each point shows the median of three cold runs on one pinned Zen 2 core, "
              "including model load, on the 730-utterance LibriSpeech DEV panel."
              f"{subset} Filled marks stream live. Hollow marks need the whole clip first. Lighter marks show interim "
              f"shared-host measurements. {watts} Results are exploratory. [Read the paper](docs/paper/paper.pdf).",
              "", LEAD, "", "See the [benchmark freeze protocol](docs/ultra/FREEZE.md).", "", *facts["bullets"], "",
              "| System | Class | Cold throughput per core (× real time) | W per always-on stream | dev-clean WER (%) | "
              "dev-other WER (%) | Pooled WER (%) | Peak memory (MB) | Host |", "|---|---|---:|---:|---:|---:|---:|---:|---|"]
    for r in sorted(drawn, key=lambda r: -derived(r)["speed"]) + extra:
        d = derived(r)
        name = (f"**{r['short']}**" + ("" if "ours" in r["short"] else " (ours)")) if r["role"] == "ours" else r["short"]
        name += ("" if r["plot"] else ", not drawn") + ("" if r["timing_panel"] == "full" else ", timed on 73 utterances")
        where = HOST_NAMES.get(r["host"], r["host"]) + (", interim" if r["interim"] else "")
        w = "—" if d["watts"] is None else fmt(d["watts"], 3)
        lines.append(f"| {name} | {r['class'].replace('_', ' ')} | {speed_text(d['speed'])} | {w} | "
                     f"{fmt(d['wer_clean'], 2)} | {fmt(d['wer_other'], 2)} | {fmt(d['wer'], 2)} | "
                     f"{fmt(d['rss_mb'], 0)} | {where} |")
    lines += ["", "Hosts: H1 is the quiet host (one timed system at a time); H0 is a shared host whose rows are interim "
              "until their H1 rows arrive. Refresh the figure, this block and the PDF with `just paper-refresh`.", END]
    return "\n".join(lines) + "\n"


def figure_digest(root: Path) -> str:
    """sha256 over the files Figure 1 is drawn from: if it changes, money.png must be exported again."""
    h = hashlib.sha256()
    for rel in FIGURE_INPUTS:
        h.update(rel.encode() + b"\0" + (root / rel).read_bytes() + b"\0")
    return h.hexdigest()


def spliced(readme: str, block: str) -> str:
    if readme.count(START) != 1 or readme.count(END) != 1:
        raise PaperDataError(f"README.md needs exactly one {START} ... {END} block for the Figure 1 image")
    return readme[:readme.index(START)] + block.rstrip("\n") + readme[readme.index(END) + len(END):]


def publish_figure(root: Path) -> None:
    """Copy the generated block into README.md and stamp money.png with the digest of its inputs."""
    block = (root / DATA / "money_readme.md").read_text(encoding="utf-8")
    readme = root / "README.md"
    readme.write_text(spliced(readme.read_text(encoding="utf-8"), block), encoding="utf-8")
    if not (root / "docs/paper/money.png").is_file():
        raise PaperDataError("docs/paper/money.png is missing; `just paper-refresh` exports it before publishing")
    (root / STAMP).write_text(figure_digest(root) + "\n", encoding="utf-8")
