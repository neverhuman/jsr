"""Figure 1 outside the PDF: the README block (data/money_readme.md) and the freshness stamp of money.png.

`just paper-refresh` exports docs/paper/money.png from figures/money_standalone.tex, then calls
`python -m tools.paper_data --publish`, which copies the generated block into README.md between its
markers and records the hash of the figure's inputs. A test compares both, so neither can go stale.
"""

from __future__ import annotations

from pathlib import Path
import hashlib

from .cold import speed_text
from .common import DATA, HOST_NAMES, PaperDataError, fmt
from .evidence import HEADLINE, derived

START, END = "<!-- money-plot:start -->", "<!-- money-plot:end -->"
FIGURE_INPUTS = ("docs/paper/data/cold_dev.csv", "docs/paper/data/money_layout.tex", "docs/paper/data/money_frontier.csv",
                 "docs/paper/figures/money.tex", "docs/paper/figures/style.tex", "docs/paper/figures/money_standalone.tex")
STAMP = "docs/paper/money.png.inputs"


def readme_block(rows: list[dict], host: str, watts: str) -> str:
    """Markdown for README.md: the image, what it shows, and the plotted numbers."""
    drawn = [r for r in rows if (r["machine"], r["threads"]) == HEADLINE and r["plot"]]
    lines = [START,
             "<!-- Generated by `just paper-refresh` from docs/paper/data/evidence/*.jsonl. Do not edit by hand. -->",
             "### Speed against accuracy on one CPU core (measured here, exploratory)", "",
             "![Speed on one CPU core against dev-clean WER on the 730-utterance LibriSpeech DEV panel, every system measured "
             "on our own hardware](docs/paper/money.png)", ""]
    if not drawn:
        lines += ["No measured rows yet.", END]
        return "\n".join(lines) + "\n"
    lines += [f"Figure 1 of [the paper](docs/paper/paper.pdf): {len(drawn)} recognisers, each decoding the same 730 "
              "LibriSpeech DEV utterances as a cold process on one pinned Zen 2 core, model load included; median of "
              "three runs. The vertical axis is WER on the panel's 400 dev-clean utterances. Further right is faster, "
              "further down is more accurate. Blue diamonds are ours; filled "
              "marks are live streaming systems, hollow marks whole-utterance systems (the whole clip first, no live "
              f"words). {host} {watts}", "",
              "| System | Class | Speed (× real time) | dev-clean WER (%) | dev-other WER (%) | Pooled WER (%) | "
              "Peak memory (MB) | Host |", "|---|---|---:|---:|---:|---:|---:|---|"]
    for r in sorted(drawn, key=lambda r: -derived(r)["speed"]):
        d = derived(r)
        name = f"**{r['short']}** (ours)" if r["role"] == "ours" else r["short"]
        where = HOST_NAMES.get(r["host"], r["host"]) + (", interim" if r["interim"] else "")
        lines.append(f"| {name} | {r['class'].replace('_', ' ')} | {speed_text(d['speed'])} | "
                     f"{fmt(d['wer_clean'], 2)} | {fmt(d['wer_other'], 2)} | {fmt(d['wer'], 2)} | "
                     f"{fmt(d['rss_mb'], 0)} | {where} |")
    lines += ["", "Refresh the figure, this block and the PDF with `just paper-refresh`.", END]
    return "\n".join(lines) + "\n"


def figure_digest(root: Path) -> str:
    """sha256 over the files Figure 1 is drawn from: if it changes, money.png must be exported again."""
    h = hashlib.sha256()
    for rel in FIGURE_INPUTS:
        h.update(rel.encode() + b"\0" + (root / rel).read_bytes() + b"\0")
    return h.hexdigest()


def spliced(readme: str, block: str) -> str:
    if readme.count(START) != 1 or readme.count(END) != 1:
        raise PaperDataError(f"README.md needs exactly one {START} ... {END} block for the Figure 1 image")
    return readme[:readme.index(START)] + block.rstrip("\n") + readme[readme.index(END) + len(END):]


def publish_figure(root: Path) -> None:
    """Copy the generated block into README.md and stamp money.png with the digest of its inputs."""
    block = (root / DATA / "money_readme.md").read_text(encoding="utf-8")
    readme = root / "README.md"
    readme.write_text(spliced(readme.read_text(encoding="utf-8"), block), encoding="utf-8")
    if not (root / "docs/paper/money.png").is_file():
        raise PaperDataError("docs/paper/money.png is missing; `just paper-refresh` exports it before publishing")
    (root / STAMP).write_text(figure_digest(root) + "\n", encoding="utf-8")
