"""Generated table bodies: the measured comparison table (data/table_measured.tex) and hardware table.

Every measured cell is a metrics.tex macro, so each number keeps its record and source. Only the
plotted release operating points and top same-dataset comparators appear in table_measured.tex.
"""

from __future__ import annotations

from .cold import macro_suffix
from .common import HOSTS, MACHINES, fmt
from .evidence import derived
from .heat import SHOW_FINAL, cell as heat_cell, scale
from .macros import tex_escape

COLUMNS = 9  # system, runtime, 1-core speed, clean/other/pooled WER, RSS, artifact, energy (J/audio-s; one macro column, the R7 hook)
_OURS_NAME = {"rc2-live-lm": "Isosyll live (160\\,ms, +LM)", "rc2-final": "Isosyll final (commit pass)"}
GROUPS = (
    ("Our method: Isosyll (single 60 MB INT8 artifact, sorted by 1-core speed)",
     lambda r: r["role"] == "ours"),
    ("Public streaming comparators (sorted by 1-core speed)",
     lambda r: r["role"] == "comparator" and r["class"] == "streaming"),
    ("Offline whole-utterance reference (sees full clip before emitting)",
     lambda r: r["role"] == "comparator" and r["class"] == "whole_utterance"),
)


def _cell(r: dict, name: str, have: bool = True, heat: dict[str, str] | None = None) -> str:
    body = f"\\Cold{r['macro']}{name}{macro_suffix(r)}" if have else "--"
    return heat_cell(heat[name], body) if heat else body


_HEAT = (  # column, derived key, log scale, higher is better
    ("Speed", "speed", True, True), ("WerClean", "wer_clean", False, False), ("WerOther", "wer_other", False, False),
    ("Wer", "wer", False, False), ("Rss", "rss_mb", True, False), ("Model", "model_mb", True, False),
    ("Watts", "watts", True, False),
)


def _heat_colours(rows: list[dict]) -> dict[str, dict[str, str]]:
    """Per-column heat-map colours over the rows of one table, keyed by row id then column name."""
    by_row: dict[str, dict[str, str]] = {r["id"]: {} for r in rows}
    for name, key, log, high in _HEAT:
        vals = [derived(r)[key] if (key != "watts" or r.get("watts") is not None) else None for r in rows]
        for r, c in zip(rows, scale(vals, log=log, higher_better=high)):
            by_row[r["id"]][name] = c
    return by_row


def _line(r: dict, heat: dict[str, str]) -> str:
    name = tex_escape(r["system"])
    if r["role"] == "ours":
        name = f"\\textbf{{{_OURS_NAME.get(r['variant'], name)}}}"
    if r.get("cite"):
        name += f"~\\cite{{{','.join(r['cite'])}}}"
    marks = ("$^{\\ddagger}$" if r["interim"] else "") + ("$^{\\S}$" if r["timing_panel"] != "full" else "")
    cells = [
        name + marks,
        tex_escape(r.get("runtime_short") or r["runtime"]),
        _cell(r, "Speed", heat=heat),
        _cell(r, "WerClean", heat=heat),
        _cell(r, "WerOther", heat=heat),
        _cell(r, "Wer", heat=heat),
        _cell(r, "Rss", heat=heat),
        _cell(r, "Model", heat=heat),
        _cell(r, "Watts", r.get("watts") is not None, heat=heat),
    ]
    return " & ".join(cells) + " \\\\"


def measured_table(rows: list[dict], extras: dict | None = None) -> str:
    out = ["% Generated by python/ultra/tools/paper_data (tables.py). Do not edit by hand.",
           "% Columns: system, runtime, 1-core speed (x RT), WER dev-clean / dev-other / pooled,",
           "% peak RSS (MB), artifact files (MB), active core W per stream."]
    plain = [r for r in rows if not r.get("anchor") and r["plot"]]
    zen_one = [r for r in plain if r["machine"] == "zen2" and r["threads"] == 1]
    shown = [r for r in plain if r["role"] != "ours" or r["variant"] in (("rc2-live-lm", "rc2-final") if SHOW_FINAL else ("rc2-live-lm",))]  # one Isosyll row: live
    heat = _heat_colours([r for r in shown if r["machine"] == "zen2" and r["threads"] == 1] or shown)
    for machine in MACHINES:
        one = [r for r in shown if r["machine"] == machine and r["threads"] == 1]
        if not one:
            continue
        out.append(f"\\multicolumn{{{COLUMNS}}}{{@{{}}l}}{{\\textbf{{{MACHINES[machine]['name']}}}}} \\\\")
        for title, pick in GROUPS:
            members = sorted((r for r in one if pick(r)),
                             key=lambda r: (-derived(r)["speed"], derived(r)["wer"]))
            if not members:
                continue
            out += ["\\midrule", f"\\multicolumn{{{COLUMNS}}}{{@{{}}l}}{{\\textit{{{title}}}}} \\\\"]
            for r in members:
                out.append(_line(r, heat[r["id"]]))
        out.append("\\midrule")
    if out[-1] == "\\midrule":
        out.pop()
    if len(out) == 3:
        out.append(f"\\multicolumn{{{COLUMNS}}}{{c}}{{no measured rows yet}} \\\\")
    return "\n".join(out) + "\n"


def always_on_table(rows: list[dict], always_on: str | None = None) -> str:
    """Quiet-host plotted rows summary (retained for generator compatibility)."""
    out = ["% Generated by python/ultra/tools/paper_data (tables.py). Do not edit by hand."]
    pick = [r for r in rows if r["threads"] == 1 and not r["interim"] and not r.get("anchor")
            and r["machine"] == "zen2" and r["plot"]]
    for r in sorted(pick, key=lambda r: (r["role"] != "ours", r.get("order", 999), derived(r)["cpu"])):
        d = derived(r)
        name = f"\\textbf{{{tex_escape(r['system'])}}}" if r["role"] == "ours" else tex_escape(r["system"])
        watts = _cell(r, "Watts", d["watts"] is not None)
        seg = {"yes": "yes", "no": "no", None: "--"}[r.get("segmenter")]
        out.append(" & ".join([name, f"\\Cold{r['macro']}CorePct{macro_suffix(r)}", watts, _cell(r, "Rss"),
                               "--", "yes" if d["speed"] > 1.0 else "no", seg]) + " \\\\")
    if len(out) == 1:
        out.append("\\multicolumn{7}{c}{no quiet-host rows yet} \\\\")
    return "\n".join(out) + "\n"


def capacity_table(rows: list[dict], cap: dict | None) -> str:
    """Capacity table retained for generator compatibility."""
    out = ["% Generated by python/ultra/tools/paper_data (tables.py). Do not edit by hand."]
    if not cap:
        return "\n".join(out + ["\\multicolumn{5}{c}{capacity test pending} \\\\"]) + "\n"
    short = {r["variant"]: r["short"] for r in rows}
    for variant, sysd in cap["systems"].items():
        for i, a in enumerate(sysd["arms"]):
            name = tex_escape(short.get(variant, variant)) if i == 0 else ""
            out.append(f"{name} & {a['streams']} & {fmt(100.0 * a['core_busy_fraction'], 0)} & "
                       f"{fmt(a['lag_p50_ms'], 0)} / {fmt(a['lag_p95_ms'], 0)} & "
                       f"{fmt(a['watts_per_stream_core'], 2)} / {fmt(a['gross_watts_per_stream_core'], 2)} \\\\")
        out.append("\\midrule")
    out.pop()
    return "\n".join(out) + "\n"
