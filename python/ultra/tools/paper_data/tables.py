def always_on_table(rows: list[dict], always_on: str | None = None) -> str:
    """One line per quiet-host one-core row drawn in Fig. 1, plus the row of ours the always-on tests ran on
    (data/systems.json headline.always_on) and newer rows of ours with their own energy line, when they are not
    drawn: the cost of keeping one stream listening."""
    out = ["% Generated by python/ultra/tools/paper_data (tables.py). Do not edit by hand.",
           "% Columns: system, share of one core (%), W per stream, kWh per stream-year, memory (MB), word lag p50 / p95,",
           "% keeps up on one core, needs a separate segmenter."]
    ref = next((r.get("order", 999) for r in rows if r["variant"] == always_on), -1)
    pick = [r for r in rows if r["threads"] == 1 and not r["interim"] and not r.get("anchor") and r["machine"] == "zen2"
            and (r["plot"] or r["variant"] == always_on  # and any newer checkpoint of ours with its own energy line
                 or (r["role"] == "ours" and r.get("watts") is not None and r.get("order", 999) <= ref))]
    for r in sorted(pick, key=lambda r: (r["role"] != "ours", not r["plot"], derived(r)["cpu"])):
        d = derived(r)
        name = tex_escape(r["system"]) + ("" if r["plot"] else "$^{\\dagger}$")
        watts = _cell(r, "Watts", d["watts"] is not None)
        quiet = MACHINES[r["machine"]]["primary_host"]
        star = "$^{*}$" if quiet is not None and (r.get("lag_host") or r["host"]) != quiet else ""
        lag = (f"{_cell(r, 'LagPfifty')} / {_cell(r, 'LagPninetyFive')}{star}" if d["lag_p50_ms"] is not None
               else "n/a" if r["class"] == "whole_utterance" else "--")
        seg = {"yes": "yes", "no": "no", None: "--"}[r.get("segmenter")]
        out.append(" & ".join([name, f"\\Cold{r['macro']}CorePct{macro_suffix(r)}", watts, _cell(r, "Rss"), lag,
                               "yes" if d["speed"] > 1.0 else "no", seg]) + " \\\\")
    if len(out) == 3:
        out.append("\\multicolumn{8}{c}{no quiet-host rows yet} \\\\")
    return "\n".join(out) + "\n"


def capacity_table(rows: list[dict], cap: dict | None) -> str:
    """The capacity test (alwayson.capacity): N live streams paced at real time on one core, per system."""
    out = ["% Generated by python/ultra/tools/paper_data (tables.py). Do not edit by hand.",
           "% Columns: system, live streams on one core, core busy (%), stable-word lag p50 / p95 (ms),",
           "% W per stream from the core's energy register (net of the idle floor / gross)."]
    if not cap:
        return "\n".join(out + ["\\multicolumn{5}{c}{capacity test pending} \\\\"]) + "\n"
    short = {r["variant"]: r["short"] for r in rows}
    for variant, sysd in cap["systems"].items():
        for i, a in enumerate(sysd["arms"]):
            name = tex_escape(short.get(variant, variant)) if i == 0 else ""
            out.append(f"{name} & {a['streams']} & {fmt(100.0 * a['core_busy_fraction'], 0)} & "
                       f"{fmt(a['lag_p50_ms'], 0)} / {fmt(a['lag_p95_ms'], 0)} & "
                       f"{fmt(a['watts_per_stream_core'], 2)} / {fmt(a['gross_watts_per_stream_core'], 2)} \\\\")
        out.append("\\midrule")
    out.pop()
    return "\n".join(out) + "\n"
