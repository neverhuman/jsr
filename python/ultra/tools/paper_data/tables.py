"""Generated table bodies: the "measured here" table (data/table_measured.tex) and the hardware table.

Every measured cell is a metrics.tex macro, so each number keeps its record and source. A cell without
a measurement prints "--". Rows are grouped by machine, then live streaming / whole utterance / ablation.
"""

from __future__ import annotations

from .cold import macro_suffix
from .common import HOSTS, MACHINES, fmt
from .evidence import derived
from .macros import tex_escape

COLUMNS = 13  # system, runtime, 3 x WER, speed at 1 and 8 cores, lag p50 / p95 / design p50, RSS, model, watts
GROUPS = (
    ("Live streaming systems (words arrive while the audio does)",
     lambda r: r["role"] != "ablation" and r["class"] == "streaming"),
    ("Whole-utterance systems (the whole clip first; lag columns: wait for the end of the clip, then infer)",
     lambda r: r["role"] != "ablation" and r["class"] == "whole_utterance"),
    ("Our weights in other runtimes (not drawn in Fig.~1)", lambda r: r["role"] == "ablation"),
)
MODE = {"intra_op": "t", "workers": "w", "processes": "p"}  # how eight cores were used, printed as a superscript


def _cell(r: dict, name: str, have: bool = True) -> str:
    return f"\\Cold{r['macro']}{name}{macro_suffix(r)}" if have else "--"


def _line(r: dict, eight: list[dict]) -> str:
    name = tex_escape(r["system"])
    if r["role"] == "ours":
        name = f"\\textbf{{{name}}}"
    if r.get("cite"):
        name += f"~\\cite{{{','.join(r['cite'])}}}"
    marks = ("$^{\\ddagger}$" if r["interim"] else "") + ("$^{\\dagger}$" if not r["plot"] and r["role"] != "ablation" else "")
    marks += "$^{\\S}$" if r["timing_panel"] != "full" else ""
    best = max(eight, key=lambda e: derived(e)["rtfx"]) if eight else None
    whole = r["class"] == "whole_utterance"
    live, design = r.get("lag_p50_ms") is not None, r.get("lag_design_p50_ms") is not None
    final = r.get("final_latency_p50_ms") is not None
    quiet = MACHINES[r["machine"]]["primary_host"]
    away = live and quiet is not None and (r.get("lag_host") or r["host"]) != quiet
    star = "$^{*}$" if away and not r["interim"] else ""  # a quiet row whose lag was measured on the shared host
    cells = [
        name + marks, tex_escape(r.get("runtime_short") or r["runtime"]),
        _cell(r, "WerClean"), _cell(r, "WerOther"), _cell(r, "Wer"), _cell(r, "Speed"),
        _cell(best, "Rtfx") + f"$^{{{MODE[best['parallel']]}}}$" if best else "--",
        _cell(r, "FinalLatencyPfifty", final) if whole else _cell(r, "LagPfifty", live) + star,
        _cell(r, "FinalLatencyPninetyFive", final) if whole else _cell(r, "LagPninetyFive", live),
        "n/a" if whole else _cell(r, "LagDesignPfifty", design),
        _cell(r, "Rss"), (_cell(r, "Installed") + "$^{\\P}$") if r.get("installed_bytes") else _cell(r, "Model"),
        _cell(r, "Watts", r.get("watts") is not None),
    ]
    return " & ".join(cells) + " \\\\"


def measured_table(rows: list[dict]) -> str:
    out = ["% Generated by python/ultra/tools/paper_data (tables.py). Do not edit by hand.",
           "% Columns: system, runtime, WER dev-clean / dev-other / pooled, speed at 1 core and at 8 cores,",
           "% word lag p50 / p95 / design p50 (ms), peak memory (MB), model files (MB), watts per live stream."]
    plain = [r for r in rows if not r.get("anchor")]
    for machine in MACHINES:
        one = [r for r in plain if r["machine"] == machine and r["threads"] == 1]
        if not one:
            continue
        out.append(f"\\multicolumn{{{COLUMNS}}}{{@{{}}l}}{{\\textbf{{{MACHINES[machine]['name']}}}}} \\\\")
        for title, pick in GROUPS:
            members = sorted((r for r in one if pick(r)),
                             key=lambda r: (r["role"] != "ours", not r["plot"], -derived(r)["speed"]))
            if not members:
                continue
            out += ["\\midrule", f"\\multicolumn{{{COLUMNS}}}{{@{{}}l}}{{\\textit{{{title}}}}} \\\\"]
            for r in members:
                eight = [e for e in plain if e["machine"] == machine and e["threads"] == 8 and e["variant"] == r["variant"]]
                out.append(_line(r, eight))
        out.append("\\midrule")
    if out[-1] == "\\midrule":
        out.pop()
    if len(out) == 3:
        out.append(f"\\multicolumn{{{COLUMNS}}}{{c}}{{no measured rows yet}} \\\\")
    return "\n".join(out) + "\n"


def hardware_table(rows: list[dict]) -> str:
    """One line per host that has a measured row: its name in the paper, the CPU, and its memory configuration."""
    out = ["% Generated by python/ultra/tools/paper_data (tables.py). Do not edit by hand.",
           "% Columns: host (name in the paper), CPU, memory configuration, rows measured there (cross-checks)."]
    seen = sorted({(r["machine"], r["host"]) for r in rows}, key=lambda mh: (list(MACHINES).index(mh[0]), mh[1]))
    for machine, host in seen:
        info = HOSTS.get(host, {"name": host, "memory": None})
        count = sum(1 for r in rows if r["host"] == host and not r.get("anchor"))
        checks = sum(1 for r in rows if r["host"] == host and r.get("anchor"))
        out.append(f"{info['name']} & {MACHINES[machine]['name']} & {info['memory'] or 'not recorded'} & "
                   f"{count} ({checks}) \\\\")
    return "\n".join(out) + "\n"


