"""First-token latency per system: how long after the first spoken word ends the first text appears.

Input: eval-lane's summary raw/latency/first_token_latency.json (schema first-token-latency/v1), computed from
the word-lag traces against the locked MFA word ends of 100 dev-clean clips; "design" excludes compute (the
algorithm's own delay), "paced" is measured with the input paced at real time on the trace host. Output: the
table body data/table_first_token.tex and \\Ftl... macros. Without the file both say "pending".
"""

from __future__ import annotations

from pathlib import Path
import json

from .common import RAW, PaperDataError, fmt, sha256_file
from .macros import tex_escape
from .records import Records

SUMMARY = RAW / "latency/first_token_latency.json"
HOLD = ("parakeet-redux-photon",)  # licence on hold: never shown
KEYS = ("design_mean_ms", "paced_mean_ms")


def load(root: Path) -> dict | None:
    if not (root / SUMMARY).is_file():
        return None
    doc = json.loads((root / SUMMARY).read_text(encoding="utf-8"))
    if doc.get("schema") != "first-token-latency/v1":
        raise PaperDataError(f"{SUMMARY}: schema {doc.get('schema')!r}, expected first-token-latency/v1")
    systems = [s for s in doc["systems"] if s["variant"] not in HOLD]
    for s in systems:
        if any(s.get(k) is not None and not isinstance(s[k], (int, float)) for k in KEYS):
            raise PaperDataError(f"{SUMMARY}: {s['variant']}: latencies must be numbers or null")
    return {**doc, "systems": systems, "digest": sha256_file(root / SUMMARY)}


def _ms(x) -> str:
    return "--" if x is None else fmt(float(x), 0)


def add_first_token(root: Path, rows: list[dict], rec: Records) -> str:
    """Record the headline numbers and return the whole first-token table float, or nothing while pending."""
    doc = load(root)
    head = "% Generated by python/ultra/tools/paper_data (latency.py). Do not edit by hand.\n"
    note = dict(label="exploratory", workload="100 locked-MFA dev-clean clips (word-lag set)",
                workload_digest=doc["digest"] if doc else "pending", source=str(SUMMARY))
    if not doc:
        rec.add("FtlSentence", "\\relax", unit="sentence", configuration="first-token latency: pending", **note)
        return head + "% pending: no verified first-token latency summary yet\n"
    names = {r["variant"]: r.get("system") or r["short"] for r in rows}
    body = [f"{tex_escape(names.get(s['variant'], s.get('label') or s['variant']))} & {_ms(s.get('chunk_ms'))} & "
            f"{_ms(s.get('design_mean_ms'))} & {_ms(s.get('paced_mean_ms'))} \\\\"
            for s in sorted(doc["systems"], key=lambda s: (s.get("design_mean_ms") is None, s.get("design_mean_ms") or 0))]
    rec.add("FtlSentence", f"\\Cref{{tab:firsttoken}} gives each system's first-token latency on {doc['clips']} clips.",
            unit="sentence", configuration="first-token latency: admitted", **note)
    return head + "\n".join([
        "\\begin{table}[t]", "\\centering",
        "\\caption{\\textbf{First-token latency}: from the end of the first spoken word (locked MFA) to the first text, "
        f"mean over {doc['clips']} dev-clean clips, in ms. Design: compute excluded; paced: the input paced at real "
        "time on the trace host. Exploratory.}", "\\label{tab:firsttoken}", "\\footnotesize",
        "\\begin{tabular}{@{}lrrr@{}}", "\\toprule", "System & Chunk (ms) & Design & Paced \\\\", "\\midrule",
        *body, "\\bottomrule", "\\end{tabular}", "\\end{table}"]) + "\n"
