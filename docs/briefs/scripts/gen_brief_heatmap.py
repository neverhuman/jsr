#!/usr/bin/env python3
"""Generate docs/briefs/src/brief-heatmap.tex from docs/paper/data/cold_dev.csv.

Computes direction-aware pastel-to-rich cell background hex colours (Emerald #A7F3D0 ->
Soft Sage #D9F99D -> Warm Cream #FEF9C3 -> Soft Peach #FED7AA -> Soft Coral #FECACA) for
every numeric cell in the CEO and CTO brief scoreboards. Every text value stays a macro
from docs/paper/data/metrics.tex; this script emits only cell-colour hex macros so the
heatmap stays 100% data-driven and automatically picks up new energy measurements (e.g. R7).
"""

from __future__ import annotations

import csv
import math
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
CSV_PATH = REPO_ROOT / "docs/paper/data/cold_dev.csv"
OUT_PATH = REPO_ROOT / "docs/briefs/src/brief-heatmap.tex"

# 5-stop soft publication heatmap ramp (worst q=0.0 -> best q=1.0), >= 8:1 contrast with #111827 ink.
STOPS = (
    (0.00, (0xFE, 0xCA, 0xCA)),  # Soft Coral (worst)
    (0.25, (0xFE, 0xD7, 0xAA)),  # Soft Peach
    (0.50, (0xFE, 0xF9, 0xC3)),  # Warm Cream (mid)
    (0.75, (0xD9, 0xF9, 0x9D)),  # Soft Sage
    (1.00, (0xA7, 0xF3, 0xD0)),  # Lush Mint Emerald (best)
)

# Exact 9 rows shown in the CEO/CTO brief scoreboards: ONLY our best fastest Isosyll + 8 public rivals.
BRIEF_ROWS = (
    ("IsoLive", "rc2-live-lm"),
    ("Zip", "r0-int8-r6"),
    ("MoonTiny", "moonshine-tiny"),
    ("VoskSmall", "vosk-small"),
    ("VoskLarge", "vosk-large"),
    ("NemoFiveSixty", "nemotron-en-560"),
    ("ParakeetOnnx", "parakeet-v3-onnxasr-int8"),
    ("WhisperTiny", "whispercpp-stream-tiny"),
    ("WhisperBase", "whispercpp-stream-base"),
)

# (macro_field, csv_column, higher_is_better, log_scale, fixed_domain_or_None)
METRICS = (
    ("Speed", "speed", True, True, None),
    ("Core", "cpu", False, True, None),
    ("Wer", "wer", False, False, None),
    ("Clean", "wer_clean", False, False, None),
    ("Other", "wer_other", False, False, None),
    ("Rss", "rss_mb", False, True, None),
    ("Model", "model_mb", False, True, None),
    ("Energy", "watts", False, True, (0.30, 5.00)),
)


def lerp_hex(q: float) -> str:
    q = max(0.0, min(1.0, q))
    for (p0, c0), (p1, c1) in zip(STOPS, STOPS[1:]):
        if q <= p1 or p1 == 1.0:
            t = 0.0 if p1 == p0 else (q - p0) / (p1 - p0)
            rgb = tuple(round(a + (b - a) * t) for a, b in zip(c0, c1))
            return f"{rgb[0]:02X}{rgb[1]:02X}{rgb[2]:02X}"
    return "FEF9C3"


def load_rows() -> dict[str, dict[str, str]]:
    out: dict[str, dict[str, str]] = {}
    with CSV_PATH.open(encoding="utf-8", newline="") as fh:
        for row in csv.DictReader(fh):
            if row["machine"] == "zen2" and row["threads"] == "1":
                out[row["variant"]] = row
    return out


def generate() -> str:
    rows_by_var = load_rows()
    selected = [(tag, rows_by_var[var]) for tag, var in BRIEF_ROWS]

    lines = [
        "% Generated by docs/briefs/scripts/gen_brief_heatmap.py from docs/paper/data/cold_dev.csv.",
        "% Do not edit by hand. Pastel-to-rich perceptual heatmap hex codes (worst #FECACA -> best #A7F3D0).",
    ]
    for field, col, higher_better, use_log, domain in METRICS:
        vals: list[tuple[str, float | None]] = []
        for tag, r in selected:
            raw = r.get(col, "").strip()
            vals.append((tag, float(raw) if raw else None))
        present = [v for _, v in vals if v is not None and (not use_log or v > 0)]
        if domain is not None:
            lo, hi = domain
            if present:
                lo = min(lo, min(present))
                hi = max(hi, max(present))
        else:
            lo, hi = min(present), max(present)
        t_lo = math.log10(lo) if use_log else lo
        t_hi = math.log10(hi) if use_log else hi
        for tag, v in vals:
            if v is None or (use_log and v <= 0):
                hex_code = "F3F4F6"
            else:
                tv = math.log10(v) if use_log else v
                frac = 0.5 if t_hi == t_lo else (tv - t_lo) / (t_hi - t_lo)
                q = frac if higher_better else (1.0 - frac)
                hex_code = lerp_hex(q)
            lines.append(f"\\newcommand{{\\Hm{field}{tag}}}{{{hex_code}}}")
    return "\n".join(lines) + "\n"


def main() -> None:
    text = generate()
    OUT_PATH.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
