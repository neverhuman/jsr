import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [evidenceFile, outputDirectory] = process.argv.slice(2);
if (!evidenceFile || !outputDirectory) {
  console.error("Usage: node generate.mjs EVIDENCE_JSON OUTPUT_DIRECTORY");
  process.exit(2);
}

const texCharacters = {
  "\\": "\\textbackslash{}", "{": "\\{", "}": "\\}", "$": "\\$",
  "&": "\\&", "#": "\\#", "%": "\\%", "_": "\\_",
  "~": "\\textasciitilde{}", "^": "\\textasciicircum{}",
};
const texEscape = (value) => value.replace(/[\\{}$&#%_~^]/g, (char) => texCharacters[char]);
const generated = "% Generated by generate.mjs from evidence.json.\n";

function readEvidence() {
  const evidence = JSON.parse(readFileSync(evidenceFile, "utf8"));
  const identifiers = new Set();
  for (const row of evidence.measurements) {
    if (!/^[a-zA-Z0-9][a-zA-Z0-9-]*$/.test(row.id ?? "") || identifiers.has(row.id)) {
      throw new Error(`Missing, invalid, or duplicate measurement ID: ${row.id}`);
    }
    identifiers.add(row.id);
    if (!evidence.configurations[row.configuration] || !evidence.workloads[row.workload]?.digest || !row.source) {
      throw new Error(`Measurement ${row.id} needs a configuration, workload digest, and source`);
    }
  }
  return evidence;
}

function coldPoints(evidence) {
  const rows = evidence.measurements.filter((row) => row.scope === "cold-dev");
  if (!rows.length) return { points: [], hardware: "" };

  const workload = rows[0].workload;
  const hardware = evidence.workloads[workload].hardware_label;
  if (!hardware || rows.some((row) => row.workload !== workload)) {
    throw new Error("Figure 1 needs one cold DEV workload with a hardware label");
  }

  const labels = new Set();
  const points = rows.map((row) => {
    const configuration = evidence.configurations[row.configuration];
    const label = configuration.figure_label ?? configuration.label;
    const cpu = row.cpu_seconds_per_audio_second;
    const wer = row.wer_pooled_pct;
    if (!label || labels.has(label)) {
      throw new Error(`Figure 1 requires a distinct label for ${row.id}`);
    }
    if (!Number.isFinite(cpu) || cpu <= 0 || !Number.isFinite(wer) || wer < 0) {
      throw new Error(`Invalid cold DEV CPU or WER for ${row.id}`);
    }
    labels.add(label);
    return { label, cpu, wer };
  });
  return { points, hardware };
}

function displayMetric(key, value) {
  if (key.endsWith("_pct") || key.endsWith("_pp")) return value.toFixed(2);
  if (key.endsWith("_mib")) return value.toFixed(1);
  if (key === "cpu_seconds_per_audio_second") return String(Number(value.toPrecision(4)));
  return String(value);
}

function numericMacros(measurements, points, hardware) {
  const values = measurements.flatMap((row) => {
    const metrics = { ...row };
    for (const key of ["peak_rss", "artifact"]) {
      const bytes = row[`${key}_bytes`];
      if (Number.isFinite(bytes)) metrics[`${key}_mib`] = bytes / 1024 ** 2;
    }
    return Object.entries(metrics)
      .filter(([, value]) => Number.isFinite(value))
      .map(([key, value]) => {
        if (!/^[a-zA-Z][a-zA-Z0-9_]*$/.test(key)) {
          throw new Error(`Unsupported metric name ${key} in ${row.id}`);
        }
        return `\\expandafter\\def\\csname paper:${row.id}:${key}\\endcsname{${displayMetric(key, value)}}`;
      });
  });
  return [generated.trimEnd(),
    "\\newif\\ifpapercoldpoints",
    points.length ? "\\papercoldpointstrue" : "\\papercoldpointsfalse",
    `\\newcommand{\\paperhardware}{${texEscape(hardware)}}`,
    "\\newcommand{\\paperhasvalue}[4]{\\ifcsname paper:#1:#2\\endcsname#3\\else#4\\fi}",
    "\\newcommand{\\papernum}[2]{\\paperhasvalue{#1}{#2}{\\csname paper:#1:#2\\endcsname}{%",
    "  \\PackageError{paper}{Missing measurement #1 / #2}{Add sourced evidence for the requested value.}}}",
    ...values, "",
  ].join("\n");
}

const plot = { left: 37, right: 234, bottom: 24, top: 130 };

function decimal(value) {
  return String(Number(value.toPrecision(6)));
}

function linearTicks(minimum, maximum, desiredCount) {
  const target = (maximum - minimum) / desiredCount;
  const power = 10 ** Math.floor(Math.log10(target));
  const step = [1, 2, 2.5, 5, 10].map((factor) => factor * power)
    .find((candidate) => candidate >= target);
  const first = Math.ceil(minimum / step);
  const last = Math.floor(maximum / step);
  return Array.from({ length: last - first + 1 }, (_, index) => (first + index) * step);
}

function cpuTicks(minimumLog, maximumLog) {
  const ticks = [];
  for (let power = Math.floor(minimumLog); power <= Math.ceil(maximumLog); power += 1) {
    for (const factor of [1, 2, 5]) {
      const log = Math.log10(factor) + power;
      if (log >= minimumLog && log <= maximumLog) ticks.push(factor * 10 ** power);
    }
  }
  const minimumDistance = (maximumLog - minimumLog) / 7;
  const spaced = [];
  for (const tick of ticks) {
    const previous = spaced.at(-1);
    if (previous === undefined || Math.log10(tick / previous) >= minimumDistance) spaced.push(tick);
  }
  if (spaced.length >= 3) return spaced;
  return linearTicks(10 ** minimumLog, 10 ** maximumLog, 5);
}

function overlaps(a, b) {
  return a.left < b.right && a.right > b.left && a.bottom < b.top && a.top > b.bottom;
}

function labelsFor(points) {
  const labelBoxes = [];
  const markerBoxes = points.map(({ x, y }) => ({
    left: x - 3, right: x + 3, bottom: y - 3, top: y + 3,
  }));
  const byWidth = [...points].sort((a, b) => b.label.length - a.label.length);
  return byWidth.map(({ label, x, y }) => {
    const width = 3.8 * label.length + 7;
    const height = 11;
    let best;
    for (let left = plot.left; left + width <= 243; left += 3) {
      for (let bottom = plot.bottom + 2; bottom + height <= 139; bottom += 3) {
        const box = { left, right: left + width, bottom, top: bottom + height };
        if (markerBoxes.some((marker) => overlaps(box, marker)) || labelBoxes.some((other) => overlaps(box, other))) continue;
        const midX = left + width / 2;
        const midY = bottom + height / 2;
        const edges = [
          { anchor: "west", tx: left + 2, ty: midY },
          { anchor: "east", tx: box.right - 2, ty: midY },
          { anchor: "south", tx: midX, ty: bottom + 2 },
          { anchor: "north", tx: midX, ty: box.top - 2 },
        ];
        for (const edge of edges) {
          const distance = Math.hypot(edge.tx - x, edge.ty - y);
          if (!best || distance < best.distance) best = { ...edge, box, distance };
        }
      }
    }
    if (!best) throw new Error(`Figure 1 has no clear position for label ${label}; shorten the figure label`);
    labelBoxes.push(best.box);
    return { label, x, y, tx: best.tx, ty: best.ty, anchor: best.anchor };
  });
}

function frontierFigure(points) {
  const lines = [generated.trimEnd(),
    "\\begin{tikzpicture}[x=1pt,y=1pt,font=\\fontsize{7.5}{9}\\selectfont,inner sep=0pt]",
    "\\path[use as bounding box] (0,0) rectangle (243,140);",
  ];

  if (points.length) {
    const logs = points.map(({ cpu }) => Math.log10(cpu));
    const logSpan = Math.max(0.25, Math.max(...logs) - Math.min(...logs));
    const xMin = Math.min(...logs) - logSpan * 0.18;
    const xMax = Math.max(...logs) + logSpan * 0.18;
    const wers = points.map(({ wer }) => wer);
    const werSpan = Math.max(3, Math.max(...wers) - Math.min(...wers));
    const yMin = Math.max(0, Math.min(...wers) - werSpan * 0.14);
    const yMax = Math.max(...wers) + werSpan * 0.17;
    const xOf = (cpu) => plot.left + (plot.right - plot.left) * (Math.log10(cpu) - xMin) / (xMax - xMin);
    const yOf = (wer) => plot.bottom + (plot.top - plot.bottom) * (wer - yMin) / (yMax - yMin);
    const coordinates = points.map((point) => ({ ...point, x: xOf(point.cpu), y: yOf(point.wer) }));

    for (const tick of linearTicks(yMin, yMax, 4)) {
      const y = decimal(yOf(tick));
      lines.push(`\\draw[black!18] (${plot.left},${y}) -- (${plot.right},${y});`);
      lines.push(`\\draw (${plot.left - 2},${y}) -- (${plot.left},${y});`);
      lines.push(`\\node[anchor=east] at (${plot.left - 4},${y}) {${decimal(tick)}};`);
    }
    for (const tick of cpuTicks(xMin, xMax)) {
      const x = decimal(xOf(tick));
      lines.push(`\\draw (${x},${plot.bottom - 2}) -- (${x},${plot.bottom});`);
      lines.push(`\\node[anchor=north] at (${x},${plot.bottom - 4}) {${decimal(tick)}};`);
    }
    const labels = labelsFor(coordinates);
    for (const { x, y, tx, ty } of labels) {
      lines.push(`\\draw[black!65,thin] (${decimal(x)},${decimal(y)}) -- (${decimal(tx)},${decimal(ty)});`);
    }
    for (const { label, tx, ty, anchor } of labels) {
      lines.push(`\\node[anchor=${anchor},fill=white,inner sep=0.7pt] at (${decimal(tx)},${decimal(ty)}) {${texEscape(label)}};`);
    }
    for (const { x, y } of coordinates) {
      lines.push(`\\fill (${decimal(x)},${decimal(y)}) circle[radius=1.8pt];`);
    }
  } else {
    lines.push("\\node at (136,81) {Matched DEV measurements pending};");
  }

  lines.push(`\\draw (${plot.left},${plot.top}) -- (${plot.left},${plot.bottom}) -- (${plot.right},${plot.bottom});`,
    "\\node at (136,5) {CPU seconds per audio second (log scale)};",
    "\\node[rotate=90] at (6,77) {Pooled DEV WER (\\%)};",
    "\\end{tikzpicture}", "");
  return lines.join("\n");
}

try {
  const evidence = readEvidence();
  const { points, hardware } = coldPoints(evidence);
  const figure = frontierFigure(points);
  const macros = numericMacros(evidence.measurements, points, hardware);
  mkdirSync(outputDirectory, { recursive: true });
  writeFileSync(join(outputDirectory, "figure1.tex"), figure);
  writeFileSync(join(outputDirectory, "metrics.tex"), macros);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
